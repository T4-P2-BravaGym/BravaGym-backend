"""T-02: the OpenAPI docs describe every tag, every error and every input."""

from app.main import app

ERROR_SCHEMA = "#/components/schemas/ErrorOut"


def operations():
    for path, methods in app.openapi()["paths"].items():
        for method, operation in methods.items():
            yield f"{method.upper()} {path}", operation


def test_every_documented_error_uses_error_out():
    missing = [
        f"{name} → {code}"
        for name, operation in operations()
        for code, response in operation["responses"].items()
        if code.startswith("4")
        and code != "422"  # FastAPI's own validation schema
        and response.get("content", {})
        .get("application/json", {})
        .get("schema", {})
        .get("$ref")
        != ERROR_SCHEMA
    ]

    assert missing == []


def test_every_endpoint_that_needs_a_login_documents_401():
    missing = [
        name
        for name, operation in operations()
        if operation.get("security") and "401" not in operation["responses"]
    ]

    assert missing == []


def test_every_input_schema_has_an_example():
    schemas = app.openapi()["components"]["schemas"]
    inputs = {
        content["schema"]["$ref"].split("/")[-1]
        for _, operation in operations()
        for content in operation.get("requestBody", {}).get("content", {}).values()
        if "$ref" in content["schema"]
    }
    # Form bodies (login, photo upload) are generated by FastAPI and have no JSON example
    missing = [
        name
        for name in sorted(inputs)
        if not name.startswith("Body_")
        and "example" not in schemas[name]
        and "examples" not in schemas[name]
    ]

    assert missing == []


def test_every_tag_has_a_description():
    tags = app.openapi()["tags"]

    assert all(tag.get("description") for tag in tags)


def test_redoc_works(client):
    assert client.get("/redoc").status_code == 200
